/**
 * Writes admin/public/logo.svg: the dot-matrix Circle of Friends (inertia/lib/dot_logo.ts) in white on
 * an Ubuntu-orange disc. The PNG favicons are rendered from it:
 *
 *   node --experimental-strip-types scripts/generate_logo.mjs 9     # coarser grid: dots survive 16/32 px
 *   for s in 16 32; do rsvg-convert -w $s -h $s public/logo.svg -o public/favicon-${s}x${s}.png; done
 *   node --experimental-strip-types scripts/generate_logo.mjs       # 13×13: logo.svg and large icons
 *   for s in 180 192 512; do rsvg-convert -w $s -h $s public/logo.svg -o public/favicon-${s}x${s}.png; done
 *
 * Ubuntu and the Circle of Friends are trademarks of Canonical Ltd.; see THIRD_PARTY_NOTICES.md.
 */
import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { circleOfFriendsDots } from '../inertia/lib/dot_logo.ts'

const here = path.dirname(fileURLToPath(import.meta.url))
const GRID = Number(process.argv[2] ?? 13)
// the shape spans ~10–90 of the box: scale it into the disc with a margin
const SCALE = 0.86
const OFFSET = (100 - 100 * SCALE) / 2

const dots = circleOfFriendsDots(GRID)
  .map(
    (d) =>
      `<circle cx="${(OFFSET + d.x * SCALE).toFixed(2)}" cy="${(OFFSET + d.y * SCALE).toFixed(2)}" r="${(d.r * SCALE).toFixed(2)}"/>`
  )
  .join('')

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100">
  <!-- monolith-nomad mark: the Ubuntu Circle of Friends as a dot matrix, white on Ubuntu orange.
       Generated by admin/scripts/generate_logo.mjs. Ubuntu and the Circle of Friends are trademarks of
       Canonical Ltd.; see THIRD_PARTY_NOTICES.md. -->
  <circle cx="50" cy="50" r="50" fill="#e95420"/>
  <g fill="#ffffff">${dots}</g>
</svg>
`
writeFileSync(path.join(here, '../public/logo.svg'), svg)
console.log(`logo.svg: ${GRID}×${GRID} grid`)
